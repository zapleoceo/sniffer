-- Когда чат последним проходил проверку живости: очередь круга живёт в БД.
--
-- Раньше номер чата в круге хранился в памяти коллектора и при каждом рестарте (деплое)
-- сбрасывался на 0: проход снова и снова брал первые чаты, хвост голодал. Теперь проход
-- берёт активный неисключённый чат с самым старым liveness_checked_at (NULL - первым).
-- Отметка ставится и после упавшего прохода, иначе недоступный чат блокировал бы круг.
--
-- Только идемпотентный DDL (tests/test_sql_chain.py); колонка есть и в теле CREATE TABLE
-- chats в 001_init.sql, ALTER ниже - для живой базы (часовой в infra/deploy.sh).
ALTER TABLE chats ADD COLUMN IF NOT EXISTS liveness_checked_at TIMESTAMPTZ;
