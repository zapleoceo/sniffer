-- Free catalog watches are independent of old Stars billing and subscriptions.
CREATE TABLE IF NOT EXISTS catalog_watch_credentials (
    tg_chat_id BIGINT PRIMARY KEY CHECK (tg_chat_id > 0),
    token_hash CHAR(64) NOT NULL UNIQUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS catalog_watches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_chat_id BIGINT NOT NULL REFERENCES catalog_watch_credentials(tg_chat_id),
    filters JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_check_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    after_id BIGINT NOT NULL DEFAULT 0,
    UNIQUE (tg_chat_id, filters)
);
CREATE INDEX IF NOT EXISTS catalog_watches_due_idx ON catalog_watches (next_check_at, id);

CREATE TABLE IF NOT EXISTS catalog_watch_delivered (
    tg_chat_id BIGINT NOT NULL REFERENCES catalog_watch_credentials(tg_chat_id),
    canonical_url TEXT NOT NULL,
    delivered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tg_chat_id, canonical_url)
);
