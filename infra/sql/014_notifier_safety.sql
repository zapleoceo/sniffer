-- Безопасность доставки (notifier): клиент заблокировал бота, причина отказа очереди.
--
-- Только DDL: цепочка применяется на КАЖДОМ деплое, и любая правка данных здесь
-- исполнялась бы после каждого следующего (docs/deploy.md, «Что можно класть в
-- infra/sql»). Обе колонки пусты у всех существующих строк, и это правильное
-- начальное состояние: «не заблокирован», «причины нет».

-- Когда бот узнал, что писать этому клиенту нельзя: HTTP 403 на sendMessage или
-- апдейт my_chat_member со статусом kicked. NULL — писать можно. Колонка, а не
-- булево: момент нужен, чтобы разбирать «с какого времени тишина», а снятие
-- блокировки (апдейт member) возвращает NULL, и слежение возобновляется само.
ALTER TABLE users ADD COLUMN IF NOT EXISTS bot_blocked_at TIMESTAMPTZ;

-- Почему строка очереди не ушла. Статус `cancelled` — наше решение не слать
-- (просрочено, клиент заблокировал бота), `failed` — Telegram отказал или
-- кончились попытки; без причины их не различить, глядя в базу.
ALTER TABLE outbox ADD COLUMN IF NOT EXISTS last_error TEXT;
