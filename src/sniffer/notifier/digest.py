"""Подборка из нескольких карточек одним сообщением: сколько влезает и где резать.

`sendMessage` принимает до 4096 знаков и на длинном тексте отвечает 400 «message is
too long». Подборка из девяти карточек (≈ 460 знаков каждая) переходила эту границу,
получала отказ и пропадала целиком — все карточки разом. Теперь подборка режется на
сообщения по границе карточки: карточка не разрывается, а подборка из нескольких
сообщений нумеруется («1 из 3»), чтобы клиент видел, что это одна подборка.

Лимит карточек в сообщении нужен и тогда, когда текст влезает: десять ссылок в одном
сообщении не прочитать, а лишнее сообщение — это секунда паузы, не проблема.

Чистые функции без ввода-вывода. Длину меряем по HTML-строке: Telegram считает знаки
уже после разбора разметки, то есть строка с тегами и `&lt;` длиннее, чем счёт
Telegram, и мы с запасом, а не впритык.
"""

from __future__ import annotations

from collections.abc import Sequence

MESSAGE_LIMIT = 4096
CARDS_PER_MESSAGE = 8
SEPARATOR = "\n\n"
TITLE = "Новые находки по вашему запросу"


def header(part: int = 1, parts: int = 1) -> str:
    """Заголовок подборки; у подборки из одного сообщения номера нет."""
    base = f"<b>{TITLE}</b>"
    return base if parts == 1 else f"{base} ({part} из {parts})"


def split(
    cards: Sequence[str], *, limit: int = MESSAGE_LIMIT, per_message: int = CARDS_PER_MESSAGE
) -> list[list[int]]:
    """Индексы карточек по сообщениям: жадно, по порядку, по границе карточки.

    Место под заголовок берётся по самому длинному — с номером «99 из 99»: сколько
    будет сообщений, известно только после разбиения, а заголовок входит в длину.
    Карточка, которая одна длиннее лимита, получает сообщение целиком для себя: резать
    её нельзя, а остальные из-за неё страдать не должны.
    """
    room = limit - len(header(99, 99)) - len(SEPARATOR)
    groups: list[list[int]] = []
    used = 0
    for index, card in enumerate(cards):
        joined = used + len(SEPARATOR) + len(card)  # длина группы, если добавить эту карточку
        if groups and joined <= room and len(groups[-1]) < per_message:
            groups[-1].append(index)
            used = joined
        else:
            groups.append([index])
            used = len(card)
    return groups
