def no_free_slot(titles: Sequence[str]) -> str:
    """Все слоты заняты: что именно можно сделать, без нажима."""
    held = ", ".join(f"«{title}»" for title in titles) or "другими поисками"
    return (
        f"Все слоты слежения заняты: {held}. Можно перенести слот на этот поиск (слежение за "
        "прежним встанет на паузу, ничего не удаляется) либо добавить ещё один слот."
    )


def move_label(title: str) -> str:
    """Подпись кнопки переноса. Название режем: кнопка в телефоне короче сообщения."""
    short = title if len(title) <= 28 else title[:27] + "…"
    return f"Перенести слот с «{short}»"
