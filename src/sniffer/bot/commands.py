"""Похоже ли сообщение на команду бота.

Нужен одному месту: запасному обработчику текста. Неизвестная команда не должна
становиться поисковой фразой (FLOW-17): «/terms» превращалась в поиск слова «terms»,
и человек получал выдачу вместо ответа, что такой команды нет. Известные команды
перехватывают свои обработчики раньше, до запасного добираются только неизвестные.

Команда Telegram — слеш и латиница, цифры, подчёркивание, возможно `@имя_бота`.
Текст, начатый со слеша иначе («/ 5 комнат», «/кв»), командой не считается и идёт в
поиск как был: человек мог просто начать фразу с него.
"""

from __future__ import annotations

import re

_COMMAND = re.compile(r"/[A-Za-z0-9_]+(?:@[A-Za-z0-9_]+)?(?:\s|$)")


def looks_like_command(text: str) -> bool:
    return _COMMAND.match(text) is not None
