"""Ветка запроса: сколько их держим в работе и какая уходит из списка.

Ветка — это цепочка версий паспорта, ключ `COALESCE(root_id, id)`. Отдельной
сущности у неё нет и быть не должно: цепочкой владеет `passports`, и вторая
таблица с тем же тождеством — это ровно то дублирование ЗНАНИЯ, которое
запрещает CLAUDE.md. Здесь живёт только то, чего в цепочке нет: предел на число
веток и правило «какая вытесняется».

Почему предел вообще нужен. Ветка — единица контекста, которую человек обязан
различать глазами: список `/requests` рисуется по кнопке на ветку, и на экране
телефона шестая строка уже уезжает под сгиб. Предел здесь — на ВИДИМЫЕ ветки, а
не на хранимые, и формулировка эта не уклончивая, а точная: вытесненная ветка
никуда не девается — её мониторинг работает, её корень по-прежнему приезжает в
кнопках под старой выдачей, и выбор такой кнопки возвращает ветку в список.
Уничтожать её при переполнении нельзя: у ветки может быть оплаченный
мониторинг, и молча закрыть оплаченное — это не предел, а потеря денег клиента.
"""

from __future__ import annotations

from collections.abc import Sequence

from sniffer.domain.records import QueryOverview

# Пять. Число взято не из красоты: столько строк кнопок читается на телефоне без
# прокрутки, и столько параллельных поисков человек ещё различает по названию.
# Шестая ветка не запрещена — она вытесняет из списка самую старую.
MAX_LIVE_THREADS = 5


def pushed_out(live: Sequence[QueryOverview]) -> QueryOverview | None:
    """Какая ветка уйдёт из списка, если открыть ещё одну. `None` — место есть.

    `live` приходит отсортированной свежими сверху и уже обрезанной пределом,
    поэтому «самая старая» — это последняя, а «мест нет» — это ровно предел.
    Считать по полному списку было бы нельзя: за пределом лежат ветки, которые
    из списка ушли раньше, и вытесняется не они.
    """
    if len(live) < MAX_LIVE_THREADS:
        return None
    return live[-1]
