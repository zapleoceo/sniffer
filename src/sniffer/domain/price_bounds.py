"""Правдоподобные границы цены по категории и стороне сделки.

Контекст сумм отсеивает сборы и залоги по словам, но слов хватает не на всё:
«Регистрация 550.000», «1,5 млн (1-2 месяца)» вместо «16,5», «2-й мотоцикл —
100 000». Общая страховка — граница здравого смысла: квартира в аренду не
стоит полторы сотни тысяч в месяц, а подержанный скутер не стоит тридцать
миллиардов. Выход за границу значит «это не цена», и честнее остаться без
цены, чем показать клиенту сбор вместо аренды.

Границы широкие намеренно: они ловят явный абсурд, а не торгуются с рынком.
Дешёвая комната в хостеле и вилла у моря обе помещаются.
"""

from __future__ import annotations

# (нижняя, верхняя) в донгах: за месяц для аренды, целиком для продажи.
_RENT: dict[str, tuple[int, int]] = {
    "apartment": (2_000_000, 150_000_000),
    "room": (1_000_000, 30_000_000),
    "house": (2_000_000, 300_000_000),
    "motorbike": (500_000, 30_000_000),
    "bicycle": (100_000, 5_000_000),
    "car": (3_000_000, 100_000_000),
}
_SELL: dict[str, tuple[int, int]] = {
    "motorbike": (1_000_000, 700_000_000),
    "bicycle": (200_000, 60_000_000),
    "car": (20_000_000, 5_000_000_000),
    "apartment": (100_000_000, 10_000_000_000),
    "house": (100_000_000, 10_000_000_000),
}


def price_bounds(category: str | None, deal_type: str | None) -> tuple[int, int] | None:
    """Границы для пары «категория, сторона» либо ``None``, если пара не известна."""
    if category is None:
        return None
    table = {"rent_out": _RENT, "sell": _SELL}.get(deal_type or "")
    return table.get(category) if table is not None else None
