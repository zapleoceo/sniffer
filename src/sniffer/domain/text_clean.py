"""Очистка текста объявления перед разбором: цифры, которые написаны не цифрами.

Продавцы прячут цену от поисковых ботов, и делают это тремя способами, которые
встречаются не по разу: «жирные» математические цифры (`𝟙𝟚 𝟝𝟘𝟘 𝕧𝕟𝕕`),
цифры-эмодзи с разделителем-значком (`1️⃣5️⃣🔣0️⃣0️⃣0️⃣`) и кириллическая «О» вместо
нуля (`5ОО.ООО`). Для человека это цена, для регулярного выражения — шум, и
карточка уходит в базу «без цены» при том, что цена в оригинале на виду.

Замер 03.10.2026 на 700 квартирах без извлечённой цены: около 4% из них —
именно эти три приёма. Поэтому очистка лежит отдельно от разбора цены: те же
цифры нужны площади и этажу, а не только деньгам.
"""

from __future__ import annotations

import re
import unicodedata

# Классы символов-значков: стрелки, технические знаки, геометрические фигуры,
# эмодзи. Диапазоны записаны 8-значными escape: короткая форма `\uXXXX` в
# редакторах и генераторах превращается в сам символ, и класс перестаёт читаться.
_SYMBOL = r"[\U00002190-\U00002bff\U0001f000-\U0001faff]"
_KEYCAP_RE = re.compile(r"(\d)\U0000fe0f?\U000020e3")
_BETWEEN_DIGITS_RE = re.compile(rf"(?<=\d){_SYMBOL}\U0000fe0f?(?=\d)")
_ZERO_WIDTH_RE = re.compile(r"[\U0000200b-\U0000200d\U00002060\U0000feff]")
_LOOKALIKE_RE = re.compile(r"(?<!\w)\d[\dОоOo.,]{1,12}[\dОоOo](?!\w)")
_LOOKALIKE_ZERO = str.maketrans("ОоOo", "0000")


def _zeroed(match: re.Match[str]) -> str:
    return match.group(0).translate(_LOOKALIKE_ZERO)


def clean_text(text: str) -> str:
    """Тот же текст, где цифры написаны цифрами, а скрытые знаки убраны.

    Порядок важен: NFKC превращает математические цифры и неразрывный пробел,
    но оставляет «кейкап» (цифра + U+FE0F + U+20E3) как есть, а значок между
    цифрами можно заменить пробелом только после того, как сами цифры стали
    цифрами.
    """
    text = unicodedata.normalize("NFKC", text)
    text = _ZERO_WIDTH_RE.sub("", text)
    text = text.replace("[", " ").replace("]", " ")  # «Цена: [ 53.000.000 ] VND»
    text = _KEYCAP_RE.sub(r"\1", text)
    text = _BETWEEN_DIGITS_RE.sub(" ", text)
    return _LOOKALIKE_RE.sub(_zeroed, text)
