"""Права тарифов: единственное место, где живут «10», «300» и «10 звёзд».

Числа здесь — константы, а не таблица тарифов и не настройка окружения. Таблица
`plans` была бы схемой под два числа, которые меняются решением владельца, а не
данными; настройка окружения расходилась бы между процессами (бот, воркер,
нотификатор читают её каждый свою). Константа в коде меняется ревью, едет тем же
деплоем и видна в диффе. Тексты клиенту, расчёт потолка и тесты берут числа
отсюда, а не повторяют их строкой: «10» в приветствии и «10» в проверке лимита
разошлись бы при первой же правке.

Модель — `docs/monetization.md`: бесплатно 10 уникальных карточек за период на
Telegram-аккаунт; подписка Stars (10 ⭐ в месяц) — до 300 карточек за период и
один слот слежения, каждая следующая подписка добавляет слот, но потолок карточек
не растёт: он один на аккаунт.
"""

from __future__ import annotations

FREE_CARDS_PER_PERIOD = 10
PAID_CARDS_PER_PERIOD = 300
# Цена одной подписки Telegram Stars: и первой (потолок 300 + слот), и каждой
# следующей (ещё один слот).
SUBSCRIPTION_STARS = 10


def card_cap(slots: int) -> int:
    """Потолок карточек периода по числу действующих подписок на МОМЕНТ выдачи.

    Хотя бы один слот — 300, иначе 10. Слотов может быть сколько угодно, потолок
    от этого не растёт. Выданное раньше не пересчитывается: подписка меняет
    потолок, а не историю.
    """
    if slots < 0:
        raise ValueError("число слотов не бывает отрицательным")
    return PAID_CARDS_PER_PERIOD if slots >= 1 else FREE_CARDS_PER_PERIOD
