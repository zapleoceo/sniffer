"""Когда объявление перестаёт быть предложением.

Каталог обязан хранить актуальное, а не всё, что когда-либо было сказано: бот
отвечает из базы, и снятое объявление в выдаче — это ложь клиенту, заметная
только когда он напишет продавцу. Признаков три, и у каждого свой исполнитель:

* **возраст** — старше `LISTING_MAX_AGE_DAYS` карточка гаснет (воркер,
  `worker/expiry.py`). Объявление, которое продавец хочет продлить, он
  переопубликует, и дедуп поднимет старую карточку на свежую дату;
* **слово продавца** — «продано», «сдано», «sold», «đã bán»: в начале текста
  или строки либо в коротком сообщении (не где угодно: «Sold with helmet» —
  это предложение). Новое сообщение с таким словом карточкой не становится
  (гейт), а отредактированное в «продано» гасится при перечитывании
  (коллектор, `collector/liveness.py`);
* **исчезновение** — сообщение удалено из чата или объявление пропало с доски
  (коллектор; обход Chotot).

Знание о словах здесь, в домене, потому что нужно оно трём слоям сразу —
воронке, коллектору и воркеру, — и ни один из них не вправе импортировать
другой.
"""

from __future__ import annotations

import re

# Сколько живёт карточка без переопубликации. Замер 18.09.2026: из 8578
# «активных» карточек 2433 были старше 30 дней — ни одна из них не гасла
# никогда, и бот предлагал бы их наравне со вчерашними.
LISTING_MAX_AGE_DAYS = 30

# Почему карточка снята с выдачи (`listings.deactivated_reason`, миграция 022). Строки
# пишутся в базу, поэтому менять их нельзя без миграции данных.
REASON_EXPIRED = "expired"
REASON_SCREEN = "screen"
REASON_LIVENESS_DELETED = "liveness_deleted"
REASON_LIVENESS_CLOSED = "liveness_closed"
REASON_SUPERSEDED = "superseded"


def unseen_reason(source: str) -> str:
    """Живой источник перестал отдавать объявление: `chotot_unseen`."""
    return f"{source}_unseen"


# Пробел без перевода строки: «фраза» не должна перепрыгивать на следующую строку.
_SP = r"[^\S\n]"

# Продавец закрыл объявление словом. Корни с концом слова, чтобы «продаю» и
# «сдаётся» (предложение!) не путались с «продано» и «сдано».
_CLOSED_WORD = (
    r"(?:продан[оаы]?|сдан[оаы]?|не\s*актуальн\w*"
    rf"|sold(?:{_SP}*out)?|no\s+longer\s+available|đã\s+bán|đã\s+cho\s+thuê)\b"
)
# Слово отдельной фразой: за ним конец строки, знак или значок, а не следующее
# слово. Так «Sold with helmet» (продаётся со шлемом) и «сдан в эксплуатацию»
# (свойство новостройки) не принимаются за закрытие; «đã bán rồi» — принимается.
_STANDS_ALONE = rf"(?=(?:{_SP}+(?:rồi|nhé|ạ))?{_SP}*(?:[^\w\s]|$))"
# «Не продано», «not sold out»: отрицание переворачивает смысл.
_NOT_NEGATED = r"(?<!\bне\s)(?<!\bnot\s)(?<!\bno\s)"
# Слово в НАЧАЛЕ строки — правка автора («ПРОДАНО Honda Vision»). Исключено
# лишь «sold with / sold by / продано вместе»: это описание комплекта.
_NOT_A_BUNDLE = r"(?!\s+(?:with|by|to|for|in|at|on|and|separately|together|с|со|вместе)\b)"

_FLAGS = re.IGNORECASE | re.MULTILINE
_AT_LINE_START = re.compile(rf"^[^\w\n]*{_CLOSED_WORD}{_NOT_A_BUNDLE}", _FLAGS)
_STANDALONE = re.compile(rf"\b{_NOT_NEGATED}{_CLOSED_WORD}{_STANDS_ALONE}", _FLAGS)

# Короткое сообщение целиком — реплика автора, а не объявление: «Квартира сдана,
# объявление не актуально». Длиннее — слово считается только в начале строки:
# посреди описания «sold» бывает чем угодно, а ложное снятие хуже запоздалого —
# возраст всё равно погасит карточку (LISTING_MAX_AGE_DAYS).
SHORT_MESSAGE_CHARS = 60


def announces_closed(text: str) -> bool:
    """Говорит ли текст, что предложение закрыто."""
    stripped = text.strip()
    if _AT_LINE_START.search(stripped):
        return True
    return len(stripped) <= SHORT_MESSAGE_CHARS and _STANDALONE.search(stripped) is not None
