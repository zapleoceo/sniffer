"""Справочник мест Нячанга и Дананга: собирает данные городов в один реестр.

Данные городов лежат в своих файлах (`districts_nha_trang`, `districts_da_nang`), а здесь
они становятся записями `Place` и словарём слов зон. Новый город — новый файл с
данными и одна строка в `CITY_DATA`; код чтения (`facts_place`) не меняется.
"""

from __future__ import annotations

from dataclasses import dataclass

from sniffer.domain.districts_da_nang import DA_NANG
from sniffer.domain.districts_nha_trang import NHA_TRANG

# Порядок вида — порядок силы: вард и район точнее ЖК, ЖК точнее улицы (улица тянется
# через полгорода и повторяется в других городах).
KIND_RANK = {"area": 0, "complex": 1, "street": 2}
# Как называют зоны Нячанга по-русски: у карточки без названия заголовок строится из них.
ZONE_NAMES = {
    "north": "Север Нячанга",
    "center": "Центр Нячанга",
    "south": "Юг Нячанга",
    "west": "Запад Нячанга",
}


@dataclass(frozen=True, slots=True)
class Place:
    """Место справочника: слаг для `listings.district`, имя для людей, зона и написания."""

    slug: str
    name: str
    city: str
    kind: str
    zone: str | None
    aliases: tuple[str, ...]


CITY_DATA = {"nha_trang": NHA_TRANG, "da_nang": DA_NANG}

PLACES: tuple[Place, ...] = tuple(
    Place(row[0], row[1], city, row[3], row[2] or None, row[4:])
    for city, rows in CITY_DATA.items()
    for row in rows
)
# Слаг однозначен на весь реестр: два города с одним слагом склеили бы районы в базе.
PLACE_BY_SLUG: dict[str, Place] = {place.slug: place for place in PLACES}

# Слова зон по-русски, по-английски и по-вьетнамски (на свёрнутом тексте). Зона названа
# только оборотом с городом или частью города: голое «центр» — торговый центр, «север» —
# ориентация окон («Ориентация: северо-восток»), и по ним зону не читаем. «Вьетнам
# Нячанг» содержит «нам Нячанг» — Южный Нячанг по-вьетнамски, — поэтому у них стоит
# левая граница слова. «На север города» — направление поездки, а не положение лота.
ZONE_PHRASES: dict[str, str] = {
    "north": (
        r"(?<!на\s)север(?:н\w+)?(?:\s+част\w+)?\s+(?:нячанг\w*|города)|"
        r"(?:на|в)\s+севере(?:\s+(?:нячанга|города))?(?![\w-])|"
        r"северн\w+\s+(?:част\w+|район\w*)|нячанг\s+север\w*|"
        r"north(?:ern)?\s+(?:part\s+of\s+)?nha\s*trang|"
        r"(?<![a-zа-я])bac nha trang|phia bac|(?<![а-я])бак нячанг"
    ),
    "center": (
        r"(?<!на\s)центр(?:а|е|альн\w+)?(?:\s+част\w+)?\s+(?:нячанг\w*|города|город)(?![\w-])|"
        r"(?:на|в)\s+(?:самом\s+)?центре(?:\s+(?:нячанга|города))?(?![\w-])|"
        r"нячанг\s+центр(?=\s+(?:от\s+)?\d)|city\s+cent(?:er|re)|"
        r"cent(?:er|re)\s+of\s+(?:the\s+)?(?:city|nha\s*trang)|central\s+nha\s*trang|downtown|"
        r"trung\s+tam\s+(?:nha\s*trang|thanh\s*pho)"
    ),
    "south": (
        r"(?<!на\s)(?:юг|южн\w+)(?:\s+част\w+)?\s+(?:нячанг\w*|города)|"
        r"(?:на|в)\s+юге(?:\s+(?:нячанга|города))?(?![\w-])|"
        r"южн\w+\s+(?:част\w+|район\w*)|нячанг\s+юг\w*|"
        r"south(?:ern)?\s+(?:part\s+of\s+)?nha\s*trang|"
        r"(?<![a-zа-я])nam nha trang|phia nam|(?<![а-я])нам нячанг"
    ),
    "west": (
        r"(?<!на\s)запад(?:н\w+)?(?:\s+част\w+)?\s+(?:нячанг\w*|города)|"
        r"(?:на|в)\s+западе(?:\s+(?:нячанга|города))?(?![\w-])|"
        r"западн\w+\s+(?:част\w+|район\w*)|нячанг\s+запад\w*|"
        r"west(?:ern)?\s+(?:part\s+of\s+)?nha\s*trang|"
        r"(?<![a-zа-я])tay nha trang|phia tay|(?<![а-я])тай нячанг"
    ),
}
# Одно слово зоны на месте названия места: «Район: центр», «— Запад», «(Phước Hải) · юг».
# Слово целиком и без дефиса: «north-facing» и «северо-запад» — ориентация окон, а не зона.
ZONE_WORDS: dict[str, str] = {
    "north": r"север|северн(?:ый|ая|ое|ом|ого)|north|northern",
    "center": r"центр|центральн(?:ый|ая|ое|ом)|center|centre|trung tam",
    "south": r"юг|южн(?:ый|ая|ое|ом|ого)|south|southern",
    "west": r"запад|западн(?:ый|ая|ое|ом|ого)|west|western",
}
# То, что содержит слово «центр», не будучи центром города: торговый, деловой, спортивный
# центр.
NOT_CENTER = (
    r"(?:торгов|делов|бизнес|медицинск|спортивн|фитнес|массаж|красот|досуг|конференц|"
    r"туристическ|дайвинг|языков)\w*[- ]+центр\w*|(?:shopping|business|medical|fitness|"
    r"sport\w*|health|convention|diving|language|trade)[- ]+cent(?:er|re)\w*|"
    r"trung tam (?:thuong mai|y te|the thao)|\bтц\b|"
    r"центральн\w+ (?:рын\w+|парк|подножк\w+)"
)
# «20 минут до центра города», «в 5 км от центра», «тише, чем в центре» — расстояние или
# сравнение, а не положение лота. «Рядом с…» и «near…» здесь не нужны: всё после них
# до конца предложения вырезает `facts_vocab.NEARBY_RE`, прежде чем зона читается.
REFERENCE_BEFORE = r"(?:до|от|чем|около|доступност\w*|from|to)[\s\-–—:]{0,3}(?:the\s+)?$"
