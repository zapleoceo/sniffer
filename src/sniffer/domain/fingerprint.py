r"""Отпечаток текста объявления — для дедупа кросспостов.

Схема (`infra/sql/001_init.sql`) с первого дня описывает `raw_messages.text_hash`
как «sha256 нормализованного текста: ловит кросспостинг одного объявления в
пять групп, где меняются только эмодзи и пробелы». Считался он при этом от
сырого текста, то есть ловил только побайтовый повтор: достаточно другого
смайлика или лишнего перевода строки — и одно и то же объявление становилось
двумя. Комментарий описывал замысел, а не код.

Что нормализуем и почему ровно это:

- **регистр** — «ПРОДАМ» и «продам» это одно слово;
- **любые несловесные символы** (эмодзи, пунктуация, переводы строк, неразрывные
  пробелы) схлопываются в один пробел — их продавцы меняют чаще всего;
- **и ничего больше**. Цифры и буквы остаются как есть: «Honda 125» и
  «Honda 150» обязаны дать разные отпечатки, а вьетнамские диакритики
  (`xe máy`) — часть слова, а не украшение. Поэтому `\W+` по Unicode, а не
  список разрешённых букв: перечислять алфавиты значит однажды забыть чужой.
"""

from __future__ import annotations

import re
from hashlib import sha256

_DECORATION = re.compile(r"\W+", re.UNICODE)


def normalized(text: str) -> str:
    """Текст без украшений и регистра. Слова и числа не трогаются."""
    return _DECORATION.sub(" ", text.casefold()).strip()


def fingerprint(text: str) -> str:
    """Отпечаток объявления. Пустой текст отпечатка не имеет."""
    return sha256(normalized(text).encode()).hexdigest()
