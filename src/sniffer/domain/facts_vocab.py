"""Как в объявлениях жилья называют удобства, питомцев и кухню — и какие строки не лот.

Здесь только знание о письме, без алгоритма: разбор лежит в `facts_amenities.py`.
Слова читаются по СВЁРНУТОМУ тексту (`facts_text.fold`): строчные, вьетнамские без
диакритики («máy lạnh» → «may lanh»), «ё» как «е». Три языка в одном списке — это
не лишнее: у одного агентства один и тот же пост идёт русским, английским и
вьетнамским подряд, а у соседнего — на одном из трёх.
"""

from __future__ import annotations

import re

# Строки-меню агентств: навигация по ЧУЖИМ объявлениям, а не описание лота. Каждая
# найдена в подвале сотен постов (замер 03.10.2026): «АРЕНДА В ЖК ОКЕАНУС» делала
# «Oceanus» районом чужой квартиры, «КВАРТИРЫ И СТУДИИ» — студией, «АРЕНДА С
# ЖИВОТНЫМИ» — разрешением на питомцев, «HOUSE IN DANANG» — Дананг в нячангском
# посте. Совпадать должна ВСЯ строка: заголовок «Аренда квартир у моря» меню не
# содержит, и факты из него читаются.
MENU_LINE_RE = re.compile(
    r"^\W*(?:дома и виллы|квартиры и студии"
    r"|аренда (?:квартир|домов|с животными|в жк \w+|до \d+ млн)"
    r"|(?:house|apartment|villa)s? in da ?nang|актуальная база жилья.*"
    r"|услуги помимо недвижимости.*)\W*$"
)

# Удобства, у которых бывает «есть» и «нет». Ключи — имена атрибутов паспорта
# (`domain.passport.CATEGORY_ATTRIBUTES`): карточка называет то же, что обещает паспорт.
# «Стирка» (услуга) в стиральную машину не входит: основа «стирал», а не «стир».
AMENITIES: dict[str, str] = {
    "balcony": r"балкон\w*|лоджи\w*|balcon\w*|loggia|ban ?cong",
    "elevator": r"лифт\w*|elevator|\blifts?\b|thang ?may",
    "pool": r"бассейн\w*|swimming pool|(?<![a-z])pools?(?![a-z])|ho ?boi",
    "gym": r"спортзал\w*|тренажерн\w*|(?<![a-z])gym(?![a-z])|фитнес\w*|fitness",
    "washing_machine": r"стирал\w*|стиральн\w*|washing machine|(?<![a-z])washer|may ?giat",
    "air_conditioner": r"кондиционер\w*|кондей\w*|сплит\w*|air[ -]?con\w*|a/c|may ?lanh|dieu ?hoa",
}
# Отрицание стоит перед предметом вплотную: «без балкона», «no elevator», «không có thang
# máy». «Без использования лифта» отрицанием не считается — там лифт как раз есть.
NEGATOR = r"(?:без|нет|no|without|khong(?: co)?|ko)"
# Слова после предмета, которыми продавец говорит «нет»: «лифт: нет», «балкона нет, но».
# «Лифтами нет проблем» к ним не относится: после «нет» обязан кончиться оборот.
ABSENT_AFTER = (
    r"(?:нет|отсутствует|отсутствуют|не имеется|no|none|khong)"
    r"(?=\s{0,2}(?:$|[,.;:()!]|но\b|зато\b|but\b))"
)
# Всё, что стоит после слов «рядом», «вокруг», «near» до конца предложения, — соседство,
# а не удобство самого лота: «Рядом: бассейн, парк» не делает бассейн его частью.
# Предложение кончается точкой С ПРОБЕЛОМ: в «Co.opmart» точка внутри слова.
NEARBY_RE = re.compile(
    r"\b(?:рядом|поблизости|возле|вокруг|nearby|near|around|close to|next to|gan)\b"
    r"[^\n;]*?(?:[.!?](?=\s|$)|$)",
    re.MULTILINE,
)
# «В гостиной нет кондиционера» — про одну комнату, а не про жильё: такое «нет» не отрицание.
PARTIAL_BEFORE_RE = re.compile(
    r"(?:в|на|in)\s+(?:the\s+)?(?:гостин|спальн|комнат|зал|кухн|living|bed|room|kitchen)\w*\W{0,3}$"
)

# Питомцы. Слова называют только предмет; вердикт даёт слово-подсказка в том же обороте.
PETS_STEM = re.compile(r"животн\w*|питомц\w*|кошк\w*|собак\w*|\bpets?\b|thu ?cung|cho ?meo")
PETS_NO = re.compile(
    r"\bбез\b|\bнет\b|\bни\b|\bне\s+(?:допуска\w*|разреш\w*|принима\w*|сда\w*|можно|пуска\w*|подходит)|"
    r"нельзя|запрет\w*|запрещ\w*|недопустим\w*|\bno\b|\bnot\b|forbid\w*|prohibit\w*|"
    r"khong|\bko\b|\bcam\b"
)
PETS_YES = re.compile(
    r"можно|разреш\w*|допуска\w*|допустим\w*|приветству\w*|friendly|allowed|welcome|"
    r"permitted|принима\w*|доплат\w*|плат\w*|surcharge|extra|\bfee\b|\+\s?\d|возможн\w*|"
    r"обговар\w*|обсужда\w*|рассматрива\w*|согласован\w*|allow\w*|okay|\bok\b|suitable|\bfor\b|"
    r"vnd|донг\w*|cho nuoi|\bnhan\b|\bnuoi\b|\bduoc\b|phu thu|chao don"
)
# «Цена 9 млн (без животных), с питомцем 9,5 млн» — это тариф, а не запрет: оборот с суммой
# про питомцев говорит о цене, и отрицание в нём «разрешено с доплатой», а не «нельзя».
PRICED_CLAUSE = re.compile(r"\d{3}|vnd|₫|млн|донг\w*|\bdong")
# Оборот кончается там, где кончается мысль: запятая и точка с запятой делят «можно с
# животными, курение запрещено» на две мысли, и «запрещено» не отнимает разрешение.
CLAUSE_SPLIT = re.compile(r"[,;|•·\n]|[.!?]\s")

KITCHEN_SEPARATE = re.compile(
    r"отдельн\w*\s+кухн\w*|кухн\w*\s+отдельн\w*|separate\s+kitchen|private\s+kitchen|bep\s+rieng"
)
KITCHEN_SHARED = re.compile(
    r"общ\w*\s+кухн\w*|кухн\w*\s+общ\w*|shared\s+kitchen|common\s+kitchen|bep\s+chung"
)
