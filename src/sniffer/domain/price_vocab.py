"""Как в этих чатах пишут цену: единицы, валюты, метки, чужие суммы, сроки.

Здесь только знание о письме, без алгоритма: разбор лежит в `price_facts.py`.
Слова взяты с живых объявлений (выборка 1900 текстов, 03.10.2026), и каждый
список объяснён тем, что без него ломалось.
"""

from __future__ import annotations

import re

# «9 000 000», «9.000.000», «15.000. 000» (продавцы ставят пробел после точки)
# и десятичные «9,5». Группы по три цифры — тысячи, всё прочее — дробь.
NUMBER = r"\d{1,3}(?:[ .,]\s?\d{3})+(?!\d)|\d+(?:[.,]\d+)?"
UNIT = (
    r"млрд|миллиард\w*|tỷ|tỉ|billion|млн|мил(?:лион\w*)?|лям\w*|лимон\w*|mln|mill\w*|mil|"
    r"triệu|trieu|tr|тыс\w*|nghìn|ngàn|ml|кк|k|к|м|m|\U0001f34b"
)
# 🍋 — «лимон», то есть миллион: «20🍋» встречается чаще, чем кажется. Хвост после
# единицы — составная сумма: «2 tỷ 300 triệu», «4 миллиона 500 тысяч», «4 миллиона 500»;
# разбирает его `price_numbers.numbers`.
CURRENCY = r"₫|vnđ|vnd|внд|dongs?|донг\w*|đ|ď|d|\$|usd|дол(?:л\w*)?|у\.?\s?е\.?|руб\w*|₽|rub|€|eur"
AMOUNT_RE = re.compile(
    rf"(?:(?P<pcur>\$|usd|€|vnd|₫)\s?)?(?P<lo>{NUMBER})"
    rf"(?:\s*(?:[-–—]|до|to)\s*(?P<hi>{NUMBER}))?"
    rf"\s*(?:(?P<unit>{UNIT})(?:\s+(?P<tail>\d{{1,3}})(?:\s*(?P<tail_unit>{UNIT}))?(?![\w]))?)?"
    rf"\.?\s*(?P<cur>{CURRENCY})?(?![\w])",
    re.IGNORECASE,
)
# Единицы, которые без валюты, метки или срока легко окажутся чем-то другим:
# «35 m» — метры, «500 ml» — миллилитры, «130к» — километры пробега.
WEAK_UNITS = frozenset({"ml", "k", "к", "m", "м"})
# Порядок важен: единицу ищут по началу слова, поэтому «миллиард» стоит выше
# «мил», «mln» и «ml» выше «m», «кк» выше «к».
_UNIT_NAMES = {
    10**9: ("млрд", "миллиард", "tỷ", "tỉ", "billion"),
    10**6: (
        "млн", "мил", "лям", "лимон", "mln", "mill", "mil", "кк", "triệu", "trieu", "tr", "ml",
        "м", "m", "\U0001f34b",
    ),
    10**3: ("тыс", "nghìn", "ngàn", "к", "k"),
}  # fmt: skip
UNIT_FACTORS = tuple((name, factor) for factor, names in _UNIT_NAMES.items() for name in names)

# Граница смысловой части строки: всё до неё к сумме не относится. Значок денег
# сам по себе метка («💰 14M VND/month»), поэтому границу запоминаем. Запятая и
# точка — границы лишь вне числа: в «19,5 млн» и «3.7tr» они десятичные.
BOUNDARY_RE = re.compile(
    r"(?:[|•·;()\[\]\U00002190-\U00002bff\U0001f000-\U0001faff]|,(?!\d)|\.(?=\s)|[!?](?=\s|$))"
    r"\U0000fe0f?"
)
MONEY = frozenset("💰💵💸💲🪙🤑💴💶💷")

# Метка цены. «Оплата» входит, «плата» — нет: «Оплата 25.000.000» — аренда, а
# «Плата за проживание» и «Плата за управление» — сборы.
# «Арендатор» и «арендодатель» — люди, а не плата: «🌍 1 иностранный арендатор —
# 6 млн» называет цену для арендатора, но не метку.
_PRICE_LABELS = (
    r"аренд(?!атор|одател)\w*|стоимост\w*|цена|цены|цену|цене|price\w*|rent\w*|cost|"
    r"giá(?:\s+thuê)?"
)
_LABEL_WORD = rf"(?:{_PRICE_LABELS}|оплата)"
# Для метки со словами между ней и суммой «оплата» не годится: «оплата клининг при
# выезде 2 млн» — это сбор, а не аренда.
_WEAK_WORD = rf"(?:{_PRICE_LABELS})"
# Метка, за которой сумма идёт сразу («Цена: 9 млн») или после пояснения с
# двоеточием («Аренда при договоре на 3 месяца: 9 млн»).
LABEL_RE = re.compile(
    rf"\b{_LABEL_WORD}(?:[^:\n]{{0,45}}:)?\s*[:—–=-]*\s*(?:от\s+|from\s+|only\s+|всего\s+)?$",
    re.IGNORECASE,
)
# Метка и несколько слов без двоеточия: «цена ремонта 2 млн», «аренда Нячанг 14.5
# млн». Цену той же вещи они называют не всегда, поэтому верим им меньше.
WEAK_LABEL_RE = re.compile(
    rf"\b{_WEAK_WORD}(?:\s+[^\W\d_]+){{1,3}}\s*[:—–=-]*\s*(?:от\s+|from\s+|only\s+|всего\s+)?$",
    re.IGNORECASE,
)
# Метка — поле, если перед ней не больше одного слова («Цена:», «Ежемесячная аренда:»)
# или после неё стоит двоеточие либо тире («DT: 48m2 - Giá: 4,5tỷ»). «Прошёл ТО
# стоимостью 4,2 млн» — слово стоит в середине фразы без всякого знака и называет
# цену детали, а не предмета: такой метке верим меньше, чем «Цена: 39 млн» ниже.
LABEL_LEAD_RE = re.compile(rf"^\W*(?:[^\W\d_]+\W+)?{_LABEL_WORD}", re.IGNORECASE)
LABEL_FIELD_RE = re.compile(r"[:—–=-]\s*(?:от\s+|from\s+|only\s+|всего\s+)?$", re.IGNORECASE)
# Строка-заголовок над списком цен: «💰 Цены:», «🟡 Условия аренды:».
# Заголовок кончается двоеточием: «НОВАЯ КВАРТИРА У МОРЯ В АРЕНДУ» — не заголовок
# списка цен, и цифры следующей строки («Чан Фу, 4») ценой не станут.
HEADER_LABEL_RE = re.compile(rf"\b{_LABEL_WORD}[^\n]{{0,40}}:\s*$", re.IGNORECASE)
# Метка вплотную к сумме, без слов между ними, и только слово «цена»: лишь ему
# верим, что голое «8.5» — миллионы. «Депозит 2, оплата 2» — это месяцы, а не
# два миллиона, хотя «оплата» тоже метка.
_PRICE_WORD = r"(?:стоимост\w*|цена|цены|цену|цене|price\w*|cost|giá)"
DIRECT_LABEL_RE = re.compile(
    rf"\b{_PRICE_WORD}\s*[:—–=-]*\s*(?:от\s+|from\s+|only\s+|всего\s+)?$", re.IGNORECASE
)
# Что стоит за числом без единицы и валюты, если это счёт, а не деньги: «3 месяца»,
# «2, 3 этаж», «6-12 мес», «2-month deposit», «3 - 6 month contract».
COUNT_AFTER_RE = re.compile(
    r"^\s*(?:[-–—/,]\s*\d+\s*)*(?:-?(?:й|я|е|ой|ый|ая|ое|st|nd|rd|th)\b)?\s*[-–—]?\s*"
    r"(?:месяц|мес\b|month|mo\b|дн|день|дней|ноч|этаж|спальн|комнат|bed|bath|ванн|"
    r"санузл|человек|гост|раз\b|шт|лет\b|год|year|day|night|нед|week|room|floor|%)",
    re.IGNORECASE,
)
# Слово сразу за числом без единицы и валюты: «2 с ванной», «2 качественных
# шлема». Такое число — не деньги, если слово не из тех, что идут за ценой: «17,8
# покупка» и «2,8/мес. аренда» под заголовком «Цена:» — цены.
WORD_AFTER_RE = re.compile(r"^\s*[-–—]?\s*[^\W\d_]")
NEUTRAL_AFTER_RE = re.compile(
    r"^\s*[-–—]?\s*(?:торг|нег|nego|включ|вкл\b|net\b|all\b|покупк|продаж|выкуп|аренд|"
    r"rent|buy|sale|sell)",
    re.IGNORECASE,
)
# Итоговая строка бота-агрегатора: «💰 9 000 000 ₫/мес #booking». Бот вынимает цену
# из того же текста и ошибается так, как ошибается любой наивный разбор: «АРЕНДА ДО
# 10 МЛН» принял за цену, площадь «72 м²» за 72 200 000 ₫. Строку не читаем вовсе:
# вместе с ценой текста она сходится почти всегда, а чего в тексте нет — то она
# выдумала (замер 03.10.2026 по 5051 такой строке).
AGGREGATOR_LINE_RE = re.compile(r"^\s*💰\s*[\d .,]+\s*₫(?:\s*/\s*мес)?\s*#\w+\s*$")
# Заголовок «В стоимость включено:» открывает список того, что входит в цену, а не
# список цен: числа под ним — шлемы, этажи и ванные.
INCLUDED_RE = re.compile(r"включ|include|входит|bao gồm", re.IGNORECASE)

# Слова, которые называют, ЗА ЧТО платят: сумма при них — сбор, а не цена предмета
# («275 000 — интернет», «залог: 10 млн», «500 000/мес за питомца»). Слова целые, а
# не основы: основа «электр» читала «электроскутер» как электричество и убивала
# цену («Продам электроскутер VinFast 12 млн», замер Opus 03.10.2026).
_PAID_FOR = (
    r"залог\w{0,2}|депозит\w{0,2}|deposits?|cọc|вод[аыуе]|water|nước|"
    r"электричеств\w*|электроэнерг\w*|э/э|electricity|electric\s+(?:bill|fee|meter)|điện|"
    r"управл\w+|менеджмент\w*|management|обслуживан\w*|сервис\w*|services?|"
    r"интернет\w*|internet|wi-?\s?fi|вывоз\w*|мусор\w*|trash|garbage|"
    r"парковк\w{0,3}|parking|уборк\w{0,3}|клининг\w*|cleaning|бель[яеёю]|стирк\w{0,3}|"
    r"laundry|комисси\w{0,3}|commission|страхов\w*|предоплат\w*|prepa\w*|кондиционер\w*|"
    r"газ|gas|штраф\w*|питомц\w*|животн\w*|pets?|кошк\w*|собак\w*|"
    r"доставк\w{0,3}|delivery|трансфер\w*|налог\w*|регистрац\w*|"
    r"резерв\w*|reserv\w*|бронь|бронирован\w*"
)
# Слова, после которых число — не цена, но которые сами суммы не описывают:
# «Торг до 10 млн», «Пробег 130к», «Тел 0905…». «Цена 10 млн, торг» — это цена.
_NOT_A_PRICE = (
    r"свет|срок\w*|term|duration|период\w*|period|скидк\w*|discount|торг\w*|пробег\w*|"
    r"mileage|курс|телефон\w*|тел|phone|zalo|whatsapp|hotline"
)
_FEE = rf"(?<!\w)(?:{_PAID_FOR})(?!\w)"
_NAMES = rf"(?<!\w)(?:{_PAID_FOR}|{_NOT_A_PRICE})(?!\w)"
# Слово называет сумму, только если стоит вплотную к ней: не дальше двух слов и
# знаков препинания. Слово из окна в восемьдесят знаков («Квартира с парковкой у
# моря … 15 млн») называло её без всякого права.
OTHER_BEFORE_RE = re.compile(
    rf"{_NAMES}(?:\s+[^\W\d_]+){{0,2}}\s*(?:[:—–=-]\s*)?[~≈]?\s*$", re.IGNORECASE
)
# Метка называет другую сделку: «Стоимость покупки 2 млн» в объявлении об аренде —
# цена покупки, а «Аренда 6 млн» в объявлении о продаже — доход от аренды. Сторона
# объявления известна только архиву и плану поиска, поэтому решает их `prices.py`.
SELL_LABEL_RE = re.compile(r"(?<!\w)(?:покупк|выкуп|purchase|buy)", re.IGNORECASE)
RENT_LABEL_RE = re.compile(r"(?<!\w)(?:аренд|rent|thuê)", re.IGNORECASE)
# Что стоит ПЕРЕД таким словом и делает его свойством предмета, а не названием
# суммы: «без комиссии 12 млн», «с парковкой 15 млн», «включая интернет».
FEATURE_BEFORE_RE = re.compile(
    r"(?<!\w)(?:без|с|со|with|without|no|free|бесплатн\w*|включая|including|incl)"
    r"\s+(?:[^\W\d_]+\s+)?$",
    re.IGNORECASE,
)
# После суммы чужой её делает единица («/кВт», «/чел») или слово из `_PAID_FOR`,
# которое ЗАКАНЧИВАЕТ предложение: «275 000 — интернет», «500 000/мес за питомца».
# Если после слова идёт двоеточие, число или длинное пояснение, это уже новое
# поле («— залог: аренда за 1 месяц»), а не название суммы. Точка после единицы
# («…/мес. Один депозит») кончает предложение: ни одна часть выражения точку не
# съедает, так что слова за ней суммы не называют; слово с отрицанием («без
# животных») тоже.
OTHER_AFTER_RE = re.compile(
    r"^\s*(?:/|за\s+|per\s+|в\s+)?\s*(?:кв\.?\s?т|квт|kwh|kw\b|кубометр|куб\b|m3|м3|"
    r"человек|чел\b|person|people|км\b|km\b|miles|кг\b|kg\b|литр|л\b|cc\b|см\b|м2|m2|"
    r"кв\.?\s?м|sqm|%|раз\b|час|hour|hr\b)"
    r"|^\s*(?:/\s*[^\s,.;+]+)?\s*(?:[—–:-]\s*)?"
    r"(?:(?!без\b|не\b|нет\b|without\b|no\b|с\b|со\b|with\b|включая|including)"
    r"[^\W\d_]+\s+){0,2}?"
    rf"{_FEE}(?:\s+[^\W\d_]+){{0,2}}\s*(?:$|[,.;)(/|•])",
    re.IGNORECASE,
)
# Слова целиком: «доплат» сидит внутри «предоплата», и «без предоплаты 12 млн»
# читалась надбавкой.
SURCHARGE_RE = re.compile(
    r"(?:\+|(?<!\w)(?:плюс|доплат\w*|extra|дополнительно))\s*$", re.IGNORECASE
)
# «АРЕНДА ДО 10 МЛН» — ссылка на подборку, а не цена: «до N» называет потолок
# запроса, а не цену предложения. Диапазон «от 8 до 10 млн» читается отдельно.
UPTO_RE = re.compile(r"(?:до|up\s+to|under|не\s+более|не\s+дороже)\s*$", re.IGNORECASE)

_PERIOD_PREFIX = r"^\s*(?:/|в\s+|за\s+|per\s+|a\s+)?\s*(?:(?:\d+|одн\w+|две|два|три|четыре)\s*)?"
# Единицы срока — целые слова: начало слова не срок. «ЦЕНА 9 млн. Место осмотра»
# читалась месячной («мес» — начало «место») и теряла цену; «ден» — «деньги».
_DAY_WORDS = r"(?:сут(?:ки|ок|ку)?|день|дня|дней|дни|day|ngày|ngay|night|ноч\w*)(?!\w)"
PERIOD_AFTER = (
    ("day", re.compile(_PERIOD_PREFIX + _DAY_WORDS, re.I)),
    ("week", re.compile(_PERIOD_PREFIX + r"(?:недел\w*|week\w*|tuần)(?!\w)", re.I)),
    ("month", re.compile(_PERIOD_PREFIX + r"(?:месяц\w*|мес|month\w*|tháng|thang|mo)(?!\w)", re.I)),
    ("year", re.compile(_PERIOD_PREFIX + r"(?:год(?:а|у|ов)?|year\w*|năm)(?!\w)", re.I)),
)
# Срок перед меткой: «посуточная аренда: 2.2 млн» — цена за сутки, хотя слова
# «сутки» рядом с суммой нет.
PERIOD_LABELLED = (
    ("day", re.compile(rf"(?:посуточн\w*|ежедневн\w*|daily)\s+{_LABEL_WORD}", re.I)),
    ("week", re.compile(rf"(?:понедельн\w*|еженедельн\w*|weekly)\s+{_LABEL_WORD}", re.I)),
)
PERIOD_BEFORE = (
    ("day", re.compile(r"(?:сутки|суток|сут\.?|день|day|посуточно)\s*[:—–=-]*\s*$", re.I)),
    ("week", re.compile(r"(?:неделя|неделю|week)\s*[:—–=-]*\s*$", re.I)),
    ("month", re.compile(r"(?:месяц\w*|мес\.?|month)\s*[:—–=-]*\s*$", re.I)),
)
# Во сколько раз цена за срок отличается от месячной. Для сравнения «дешевле»,
# а не для расчёта: у байка месяц обычно дешевле тридцати суток.
TO_MONTH = {"day": 30, "week": 4, "month": 1, "year": 1 / 12}
