"""Куда команда `auth` кладёт полученную строку сессии.

Отдельным модулем, потому что это **промежуточное хранилище**, а не часть
диалога авторизации. Целевое место — зашифрованная строка в нашей БД (так
сделано у Веры на соседнем проекте: секрет не лежит открытым ни в выводе, ни на
диске, и владельцу нечего переносить руками). Слой `db/` уже есть; ждём таблицы
сессий в `infra/sql/001_init.sql` и шифрования секретов. Когда появятся,
заменяется этот файл целиком, а `auth.py` не меняется.
Отступление от правила «`StringSession` живёт в БД» зафиксировано в CLAUDE.md,
раздел «Работа с Telegram».

Почему файл, а не stdout: весь вывод контейнера забирает драйвер `json-file`
из `docker-compose.yml` и кладёт в `/var/lib/docker/containers/<id>/`. Машина
общая с Верой и Степаном, лог переживает и `--rm`, и аварийное прерывание, и
его читает любой сборщик. Путь к файлу через такой лог пройти может, секрет —
нет.
"""

from __future__ import annotations

import os
from pathlib import Path

DEFAULT_SESSION_FILE = "tg_session.txt"


def why_cannot_write(path: Path) -> str:
    """Почему в этот файл не выйдет записать. Пустая строка — выйдет.

    Проверяется ДО входа в Telegram: иначе авторизация на аккаунте уже создана,
    а сохранить её некуда — худший из возможных исходов.

    **Функция обязана возвращать строку при любом пути, а не бросать.** Её
    зовут до `try` в `auth.py`, поэтому исключение отсюда — это rc=1 с
    трейсбеком, которого нет в таблице кодов `deploy.md`. А бросать `exists()`
    умеет: `Path._ignore_error` глотает только ENOENT, ENOTDIR, EBADF и ELOOP,
    остальное выходит наружу. Реальный случай — каталог без права обхода:
    `install -d -m 700 secrets` без `-o 1000 -g 1000` из инструкции по
    развёртыванию, и `stat` на файл внутри отвечает EACCES. Нужное сообщение
    («в каталог нет права записи», rc=5) при этом было тут же, но до него не
    доходило: `exists()` стоял первым.

    Порядок проверок поэтому обратный интуиции: сперва каталог, потом сам
    путь. Каталог виден без права обхода себя (`stat` на него требует прав от
    ЕГО родителя), а `os.access` не бросает вовсе — так недостаток прав
    называется своим именем раньше, чем на нём споткнётся `exists()`.
    """
    try:
        if not path.parent.is_dir():
            return f"каталога {path.parent} нет"
        # Записать файл в каталог — это и w (создать запись), и x (войти).
        if not os.access(path.parent, os.W_OK | os.X_OK):
            return f"в каталог {path.parent} нет права записи или обхода"
        # `is_symlink()` идёт по lstat и первым намеренно: `exists()` ходит по
        # симлинку, поэтому битый считает пустым местом (а `O_EXCL` потом всё
        # равно откажет — уже после всего диалога авторизации), а на симлинке
        # в закрытый каталог падает с EACCES вместо ответа.
        if path.is_symlink() or path.exists():
            return f"{path} уже существует (файл или симлинк) — удалите или укажите другой путь"
    except (OSError, ValueError) as err:
        # Остаток: ENAMETOOLONG, петля симлинков глубже ELOOP-порога, нулевой
        # байт в пути (это ValueError). Причину называем как есть — она
        # понятнее и полезнее, чем rc=1 и стек.
        return f"путь {path} не проверить ({type(err).__name__}: {err})"
    return ""


def write_session(path: Path, session: str) -> None:
    """Файл 0600 и только новый.

    `O_EXCL` не даёт ни перезаписать чужой файл, ни пройти по подсунутому
    симлинку в чужой каталог. Режим в `os.open` umask может только урезать, но
    не расширить, поэтому прав шире 0600 не получится ни при каком umask.
    """
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(f"{session}\n")
    except OSError:
        # Диск кончился на записи или на закрытии — остаётся пустой огрызок,
        # и советуемый повтор упрётся в собственный `O_EXCL` («уже
        # существует»), хотя вторая авторизация на аккаунте уже создана.
        # Убираем за собой; саму ошибку отдаём выше как есть.
        path.unlink(missing_ok=True)
        raise
