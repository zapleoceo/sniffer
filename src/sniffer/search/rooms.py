"""Число комнат из текста — запроса клиента и объявления.

Отдельным файлом по образцу `engine_size.py`, и по той же причине: число комнат
— атрибут-ЧИСЛО, а не слово-значение из `ATTRIBUTE_TERMS` (там «автомат» — слово,
а «2 спальни» это два). Знание одно, читают его двое — разбор запроса
(`intake_rules.detect_rooms`) и отбор находок перед показом (`relevance`), — как
у объёма двигателя. Разложи его по обоим слоям, и однажды поправят только один.

Голое число комнатой НЕ считается. «2» без слова рядом — это что угодно (год,
цена, число владельцев, минут до моря), и на стороне лота ложно прочитанное
число выбросило бы верный лот. Комнатой считается либо разговорное имя по числу
комнат («студия», «двушка»), либо число, ПРИЖАТОЕ к слову комнаты («2 спальни»,
«2BR», «2-комнатная», «1 bedroom»). Тем модуль и отличается от `answers._rooms`,
где вопрос «сколько комнат?» уже задан и голое «2» в ответе безопасно: там
контекст известен, здесь — нет.
"""

from __future__ import annotations

import re

# Правдоподобные границы. Ниже 1 комнаты не бывает, выше 9 — это уже не число
# комнат, а чужое число, прижавшееся к слову случайно.
MIN_ROOMS = 1
MAX_ROOMS = 9

# Разговорное имя квартиры по числу комнат: одно слово — один ответ. Те же корни
# распознают КАТЕГОРИЮ жилья (`intake_rules._CATEGORY_RULES`), но там они говорят
# «это жильё», а здесь — «столько комнат»: одно знание, два применения, а не
# копия. «студия»/«studio»/«однушка»/«однокомнатная» — одна; «двушка» — две;
# «трёшка» — три.
_WORD_ROOMS: tuple[tuple[int, re.Pattern[str]], ...] = (
    (1, re.compile(r"\b(?:студи\w*|studio|однушк\w*|одноком\w*)\b", re.IGNORECASE)),
    (2, re.compile(r"\b(?:двушк\w*|двухком\w*)\b", re.IGNORECASE)),
    (3, re.compile(r"\b(?:тр[её]шк\w*|тр[её]хком\w*)\b", re.IGNORECASE)),
)

# Число, прижатое к слову комнаты. Пробел или дефис между ними необязательны:
# рынок пишет «2 спальни», «2-комнатная», «2BR», «3bed», «2спальни» вперемешку.
# Слово ОБЯЗАТЕЛЬНО — `(?<!\d)\d` без слова комнатой не считается. «спал(?:ьн|ен)»
# ловит и «спальни», и «спален»; «bed\b»/«br\b» целым — иначе «2 bedroom» дало бы
# заодно «bed», а «2 brand» — ложное «br». «bathroom» безопасен: слово-единица
# обязано начинаться сразу за числом, а не искаться где-то дальше.
_ROOM_UNIT = r"(?:спал(?:ьн|ен)\w*|комнат\w*|бедрум\w*|bedroom\w*|bed\b|br\b|room\w*)"
_NUM_ROOMS_RE = re.compile(r"(?<!\d)(\d{1,2})[\s-]*" + _ROOM_UNIT, re.IGNORECASE)


def room_counts(text: str) -> list[int]:
    """Названные числа комнат — в порядке появления, без повторов.

    Число, ПРИЖАТОЕ к слову («2 спальни»), — сильный сигнал и главнее
    разговорного имени; разговорное («студия», «двушка») читается ТОЛЬКО когда
    прижатого числа нет вовсе. Причина — из замера снимка: у агентских
    объявлений в подвале стоит меню видов жилья («КВАРТИРЫ И СТУДИИ», 17 лотов из
    200), и слово «студии» там — навигация, а не описание ЭТОГО лота. «2 спальни»
    в теле такой рекламы не бывает, поэтому прижатое число подвал не пачкает:
    75 лотов замера с чистой «(2,)», 35 с «(3,)», и лишь 2 с конфликтом. Та же
    дисциплина, что у объёма двигателя: явное число экземпляра бьёт справочную
    догадку (`engine_size`). На коротком запросе клиента меню нет, и обе половины
    дают одно и то же.
    """
    numbered = [
        (match.start(), int(match.group(1)))
        for match in _NUM_ROOMS_RE.finditer(text)
        if MIN_ROOMS <= int(match.group(1)) <= MAX_ROOMS
    ]
    hits = numbered or [
        (match.start(), value) for value, pattern in _WORD_ROOMS for match in pattern.finditer(text)
    ]
    ordered: list[int] = []
    for _, value in sorted(hits):
        if value not in ordered:
            ordered.append(value)
    return ordered


def read_rooms(text: str) -> int | None:
    """Число комнат из запроса клиента: первое названное. `None` — не названо."""
    counts = room_counts(text)
    return counts[0] if counts else None
