"""Объём двигателя из фразы клиента. Он же — защита бюджета от кубиков.

Живой отказ 01.09.2026. Клиент написал «найди мне моцокил 200 кубиков», бот
понял «бюджет до 200000 VND» (семь долларов) и не нашёл ничего. Клиент поправил
дословно: «не 200000 VND, а обьем мощность двигателя до 200 кубических
сантиметров» — и получил тот же самый бюджет 200000 VND второй раз.

Причина не в модели, а в схеме разбора: поля под объём двигателя в ней не было
вовсе, а `budget_max` было. Модель положила число туда, где для него нашлось
место. **Модель не виновата, когда единственное числовое поле — цена.**

Поэтому лечение двойное и порядок важен. Сначала объём вынимается регулярным
выражением — это точнее и дешевле модели, — и **вырезается из текста до того,
как за него возьмётся разбор бюджета**. Потом уже в схеме появляется своё поле,
чтобы модель не изобретала.

Слова собраны из того, как это пишут на самом деле: «200 кубиков», «200 куб.
см», «200 кубических сантиметров», «200cc», «200 cm3», «объём 200». Латиница и
кириллица вперемешку — обычное дело в русскоязычном чате Нячанга.
"""

from __future__ import annotations

import re

# Правдоподобные границы для мотобайка. Ниже 49 — это уже не двигатель, а
# опечатка; выше 2000 — не тот транспорт, за которым сюда приходят.
MIN_CC = 49
MAX_CC = 2000

_CC_WORDS = r"(?:кубик\w*|куб\.?\s*см|кубических\s+сантиметр\w*|куб\w*|cc|cm3|см3|сс)"
_ENGINE_RE = re.compile(
    r"(?:(?:объ[её]м\w*|мощност\w*)\s*(?:двигател\w*)?\s*)?"
    r"(?:до|от|около|примерно)?\s*"
    r"(?P<value>\d{2,4})\s*" + _CC_WORDS,
    re.IGNORECASE,
)


def read_engine_cc(text: str) -> int | None:
    """Объём двигателя в кубических сантиметрах либо `None`."""
    for match in _ENGINE_RE.finditer(text):
        value = int(match.group("value"))
        if MIN_CC <= value <= MAX_CC:
            return value
    return None


def without_engine_cc(text: str) -> str:
    """Тот же текст без упоминаний объёма.

    Нужен разбору бюджета: «200 кубиков» и «до 200» отличаются только словом
    после числа, и если это слово убрать вместе с числом, спутать их станет
    не с чем. Убираем ТОЛЬКО правдоподобные объёмы — «5000 кубиков» это не
    двигатель, и вырезать оттуда число значило бы потерять цену.
    """

    def cut(match: re.Match[str]) -> str:
        value = int(match.group("value"))
        return " " if MIN_CC <= value <= MAX_CC else match.group(0)

    return " ".join(_ENGINE_RE.sub(cut, text).split())
