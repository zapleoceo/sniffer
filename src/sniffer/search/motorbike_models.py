"""Модельный ряд мотобайков — таблица, а не логика.

Отдельным файлом от `market_terms.py`, и не только из-за размера. Знание здесь
другого рода: словарь рынка отвечает «какими словами торгуют», а эта таблица —
«что за предмет скрыт за именем». У Honda Lead коробка не бывает механической,
поэтому вопрос «автомат или механика?» клиенту, назвавшему Lead, — это вопрос о
том, что уже известно.

Почему таблица вообще появилась: в паспорте не было понятия МОДЕЛИ. Марка и
модель лежали в одном списке вперемешку, побеждало первое совпадение regex, и
на «honda lead» побеждала «honda» — модель терялась, искали все Хонды, клиент
получал Airblade (жалоба владельца 02.09.2026).

Откуда взяты значения — по той же дисциплине, что у соседних таблиц: замер,
текст объявлений и полевые заметки не равны по силе, и отличать их обязательно.

- **перепись 31.08.2026** (spec-v2, 4.1.1): все 59 объявлений Нячанга разобраны
  руками по моделям, и деление на вариаторы и не-вариаторы взято оттуда — Lead,
  Vision, Air Blade, PCX, Vario, NVX, Nouvo автоматы; Winner, Wave, Exciter,
  Sirius нет. Это ОСНОВАНИЕ того замера, а не его результат: поля модели у
  Chotot нет, сверять было не с чем.
- **справочное знание**: Janus, Vespa, Klara и ВСЕ написания. Живым запросом не
  проверено ни одно — в отличие от `BOARD_QUERY_HITS`, где у каждого слова
  стоит число. Пометка обязательна: таблица, в которой замер неотличим от
  догадки, через полгода станет догадкой целиком.
- **замер частоты по базе Нячанга (realcheck 03.09.2026)**: Attila, R15, Click,
  Hermosa. Измерено их ИМЯ, а не устройство: каждое реально встречается в базе
  2044 лотов (attila 188, r15 110, hermosa 26, click 9) — это не догадка «такая
  модель, наверное, есть». Но замер отвечает ровно «имя на рынке есть», и не
  больше. Кузов и коробку у них по-прежнему даёт справочное знание выше: поля
  модели у Chotot нет, и что Attila — вариатор, а R15 — механика (côn tay),
  живым запросом доски не проверено. Смешивать две силы нельзя: «встретилось 188
  раз» доказано, «вариатор» — нет.
- **представительный объём (`engine_cc`)**: справочное знание, и вдобавок
  ОГРУБЛЁННОЕ — этим оно слабее даже кузова. У модели не одно значение, а ряд
  (Air Blade — 110 и 125, NVX — 125 и 155), и в таблице стоит ОДНО частое число, а
  не диапазон. Живым замером Chotot не проверено: поля объёма у модели там нет,
  есть `motorbikecapacity` корзиной. Поэтому число годится расставить модель по
  КЛАССУ («R15 — это 155, а не 250»), а не спорить о ±10 см³, и работает оно только
  на пустое место: явный объём в тексте лота (`engine_size.listing_cc_values`)
  главнее — там объём этого экземпляра, а тут догадка о ряде. Честный ответ на «от
  250» — что ни Lead (110), ни R15 (155) под него не подходят, и точности класса
  для этого хватает. Электро (`klara`) объёма не имеет вовсе — `None`, как и
  коробки: у `xe điện` его физически нет.
- **спортивные семейства (realcheck 03.09.2026)**: cbr, cb, rebel, crf, xr, mt,
  r3, r25, fz, ninja, z, zx, gsx, raider, duke, rc, monster, panigale. В каталоге
  Нячанга ~12% лотов — мотоциклы, а узнавания не было: «honda cbr» возвращал
  чужой скутер (PSX), «kawasaki z300» — вообще ничего. Основание — как у Attila:
  измерено ИМЯ (формы cbr150r, cb1000r, kawasaki z800, mt-15, yamaha fz150, ninja
  400, duke 390, ducati monster 797 — все с живых объявлений снимка). Кузов у всех
  côn tay → механика, и это СПРАВОЧНОЕ знание, не замер: спорт, нейкед, круизёр,
  эндуро — с ручным сцеплением, но живым запросом доски это не проверено, как и у
  janus. `engine_cc` у всех `None`, и не как пропуск, а как единственно честное:
  объём этих моделей стоит в САМОМ имени и у семейства РАЗНЫЙ (CBR150 против
  CBR650, Z300 против Z900), одно число соврало бы на всех членах, кроме одного.
  Настоящий объём читается из числа лота (`listing_cc_values`), а где числа нет —
  «неизвестное ≠ несовпадение». Это первый случай, когда `None` у объёма стоит НЕ
  у электро, и структурный тест таблицы (`test_every_model_declares_a_displacement
  _or_an_honest_none`) это теперь разрешает механике, но не скутеру.

Чего здесь намеренно нет. Полный модельный ряд рынка не выписывается: каждое
лишнее имя — риск поймать модель там, где её нет, а ложная модель означает, что
клиенту отрежут верную выдачу (`search/relevance.py`). Неузнанная модель
возвращает прежнее поведение — поиск по марке, — а не ломает новое. Двухбуквенное
имя как ЦЕЛОЕ слово по-прежнему под запретом — «SH» встречается в тексте
случайно; но короткое имя семейства (cb, mt, z, fz, xr, rc), СЛИПШЕЕСЯ с объёмом
или прижатое к марке, случайным уже не бывает — «cb1000r», «kawasaki z300» — и
такое имя внесено с якорем (`pattern`), а не отвергнуто. Разница не в длине, а в
том, доказывает ли контекст, что это модель: голое «cb» не доказывает, «cb1000r»
доказывает.

Измеренное, но НЕ внесённое — записано отдельно, потому что «его же сто раз в
базе» будущий читатель прочтёт как забывчивость, а не как решение:

- **candy** (Kymco Candy, 103). «candy» — обычное английское слово, брендовое имя
  (стиральные машины Candy встречаются в объявлениях о жилье) и название краски
  на самих байках («màu candy»). Охват даёт только латинское «candy», и оно же
  ложно совпадает по всем трём осям сразу: на лоте это подняло бы ложную модель и
  отрезало верную выдачу — тот же довод, что у «SH». Сузить не до чего: у Klara
  безопасной осталась латиница, а здесь ложна как раз она.
- **excel** (SYM Excel, 41). Марка ясна (SYM), а кузов — нет. Коробка следует из
  кузова, поэтому внести модель значит записать коробку; записать её, не
  проверив, — выдать догадку за замер, что этот файл и запрещает. Появится
  проверенный кузов — появится и строка.
"""

