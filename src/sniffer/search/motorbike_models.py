    """Модель: чья она, что это за предмет, как её пишут и какого она объёма.

    `spellings` — написания, по которым модель узнают в тексте. Пробел в
    написании означает «пробел здесь может быть, а может не быть»: «air blade» и
    «airblade» — одно имя, и хранить оба строками значило бы однажды забыть
    третье. Написания экранируются и ищутся как ЦЕЛОЕ слово (`\\bимя\\b`).

    `engine_cc` — представительный объём двигателя в см³. Справочно и огрублённо:
    у модели ряд вариантов, а здесь одно частое число (провенанс — в шапке файла).
    `None` — объёма нет (электро) либо он неизвестен. Пятая колонка таблицы ниже
    — это оно.

    `pattern` — сырое регулярное выражение вместо `spellings`, и это не удобство,
    а другое знание. Написание скутера — целое слово («lead», «vision»), и
    `\\bслово\\b` ему в самый раз. Имя же спортивного семейства в объявлении
    СЛИПАЕТСЯ с объёмом («cbr150r», «z300», «mt15») — целого слова там нет, и
    хвостовой `\\b` его не поймал бы. Поэтому у таких моделей recognition задаётся
    явным regex: где семейство короткое и ловится в чужих словах («cb», «mt»,
    «z», «fz») — с якорем по цифре объёма или по слову марки. `None` — модель
    ищется по `spellings`; задано — `spellings` не участвует. Выбор виден у каждой
    строки, а не спрятан во флаге: ложная модель режет верную выдачу, и почему имя
    поймано именно так — обязано читаться там же, где имя.
    """

