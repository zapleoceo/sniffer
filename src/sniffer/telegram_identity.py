"""Как мы подписаны в Telegram → Настройки → Устройства. Одно значение на всех.

Модуль существует ровно из-за того, что списку устройств всё равно, какой наш
модуль создал клиента. Telegram считает устройством **пару (auth key, подпись
клиента)**: один и тот же `StringSession`, поднятый с другим `device_model`,
показывается там ВТОРОЙ строкой, как будто вошли заново. Владелец, решая, какую
сессию отозвать, видит два сеанса вместо одного и не знает, который свой.

Клиента создают два места и по разным поводам: `collector/client.py` — разовый
вход за строкой сессии, `sources/telegram_client.py` — боевое чтение по этой
строке. Пока константы лежали в первом, второй просто не передавал их вовсе.
Такое расхождение не ломает ни один тест и не пишет ни строчки в лог: его
замечают месяцем позже по лишнему устройству в списке. Поэтому подпись живёт
здесь — там, где её видят оба, — а `test_telegram_identity.py` сверяет, что оба
клиента представляются одинаково.

Модуль-лист: не импортирует ничего из проекта, поэтому обратной зависимости
между `collector` и `sources` не появляется.
"""

from __future__ import annotations

from typing import Final

DEVICE_MODEL: Final = "SnifferBot collector"
SYSTEM_VERSION: Final = "docker"
APP_VERSION: Final = "0.1"

# Именованный набор — чтобы вызывающий не переписывал три ключа руками и не
# забыл один из них, как это уже случилось с читателем.
IDENTITY: Final[dict[str, str]] = {
    "device_model": DEVICE_MODEL,
    "system_version": SYSTEM_VERSION,
    "app_version": APP_VERSION,
}
