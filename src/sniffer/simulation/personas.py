"""Пять персон: как разные люди на самом деле пишут боту.

Отдельно от `scenarios.py`, и не по объёму. Там сценарии сгруппированы по
ПРЕДМЕТУ спора — модель, объём, город, жильё, — и каждый проверяет одно
свойство разбора. Здесь группировка по ЧЕЛОВЕКУ: одна персона пишет несколько
раз, по-своему, и ценность в том, что её манера постоянна. Терсовый не начнёт
писать развёрнуто, а опечаточник не перестанет ошибаться, и дефект, который
видно только на такой связке, в предметной таблице не появится.

Все формулировки выведены из журнала бота (`client_requests`, 45 запросов трёх
клиентов на 03.09.2026), а не придуманы. Что в нём видно и что отсюда следует:

- **голое название модели без всего остального** — `Kawasaki z300`, `Honda cbr`,
  `Adv`. Два клиента из трёх писали ТОЛЬКО так: ни города, ни бюджета, ни слова
  «мотоцикл». Значит выдача обязана держаться на одном названии;
- **опечатки в главном слове** — «моцокил», «потоцикл», «обьем». Не в
  украшениях, а именно в том слове, по которому определяется категория;
- **поправка боту** — «не 200000 VND, а обьем мощность двигателя до 200
  кубических сантиметров». Клиент увидел, что его поняли не так, и объясняет
  ЧТО именно не так. Такое сообщение обязано менять паспорт, а не читаться
  повтором;
- **расплывчатое и торопливое** — «привет», «нужен скутер», «а покажи самые
  дешевый скутеры которые есть на продажу», «какие есть сейчас». Ни города, ни
  бюджета, зато превосходная степень и требование показать сразу;
- **жильё многими условиями** — в журнале это `cat=apartment` с городом и
  бюджетом; человек называет комнаты, мебель и вид, а потом передумывает.

Числа `max_questions_before_results` здесь не смягчены под текущее поведение:
это правило продукта («больше одного вопроса до выдачи — бот тупит»), и если
персона его пробивает, красное показывает дефект, а не завышенное ожидание.
"""

from __future__ import annotations

from sniffer.domain.dialogue import SKIP
from sniffer.simulation.script import Says, Scenario, Taps, Wish

# ── 1. Терсовый: пишет только название модели, латиницей, и ничего больше ────
#
# Самая частая манера в журнале и самая беспощадная к разбору: одно слово, и по
# нему надо понять категорию, класс и то, что спрашивать почти нечего.

TERSE = (
    Scenario(
        key="terse_z300",
        title="«Kawasaki z300» — только модель, латиницей, ничего больше",
        steps=(Says("Kawasaki z300"), Taps("nha_trang"), Taps(SKIP)),
        max_questions_before_results=2,
        expect={
            "category": "motorbike",
            "attributes.brand": "kawasaki",
            # Модель — СЕМЕЙСТВО (`z`), объём — отдельным полем. Так и задумано
            # в таблице моделей: у семейства объём разный (Z300 против Z900), и
            # одно число в таблице соврало бы на всех, кроме одного. Мой первый
            # вариант ждал модель `z300` — это было неверное ожидание, а не
            # дефект бота.
            "attributes.model": "z",
            # А вот это дефект, и он был: объём из имени читала только сторона
            # ЛОТА, а сторона клиента нет, и Z300 с Z900 давали один паспорт.
            "attributes.engine_cc": 300,
        },
        # Число в имени модели — не бюджет: живой отказ 02.09.2026, клиент
        # искал 300 кубов и получил 50cc «до 300 долларов».
        forbid=("budget.max",),
    ),
    Scenario(
        key="terse_cbr",
        title="«Honda cbr» — марка и семейство без номера",
        steps=(Says("Honda cbr"), Taps("nha_trang"), Taps(SKIP)),
        max_questions_before_results=2,
        expect={"category": "motorbike", "attributes.brand": "honda", "attributes.model": "cbr"},
        forbid=("budget.max",),
    ),
    Scenario(
        key="terse_adv",
        title="«Adv» — одно слово, ни марки, ни категории",
        steps=(Says("Adv"), Taps("nha_trang"), Taps(SKIP)),
        max_questions_before_results=2,
        expect={"attributes.model": "adv"},
        forbid=("budget.max",),
    ),
)

# ── 2. Опечаточник: ошибается в ГЛАВНОМ слове ────────────────────────────────
#
# «моцокил» и «потоцикл» — из журнала дословно. Опечатка не в украшении, а в том
# слове, по которому берётся категория: не узнав его, бот теряет запрос целиком.

TYPING = (
    Scenario(
        key="typo_250_minimum",
        title="«нужен потоцикл 250 кубиков минимум» (опечатка + порог снизу)",
        steps=(Says("нужен потоцикл 250 кубиков минимум"), Taps("nha_trang"), Taps(SKIP)),
        max_questions_before_results=2,
        expect={"category": "motorbike", "attributes.engine_cc": 250},
        # «250 кубиков» — объём, а не двести пятьдесят донгов и не бюджет.
        forbid=("budget.max",),
    ),
    Scenario(
        key="typo_volume_word",
        title="«обьем до 200 кубиков, скутер» (опечатка в слове «объём»)",
        steps=(Says("обьем до 200 кубиков, скутер"), Taps("nha_trang"), Taps(SKIP)),
        max_questions_before_results=2,
        expect={"category": "motorbike", "attributes.engine_cc": 200},
        forbid=("budget.max",),
    ),
)

# ── 3. Поправляющий: объясняет боту, что его поняли не так ───────────────────
#
# Из журнала дословно. Ценность сценария не в разборе фразы, а в том, что
# поправка обязана СМЕНИТЬ факт: прочитать её повтором значит выбросить то, что
# клиент только что объяснил, и он увидит ту же неверную выдачу второй раз.

CORRECTING = (
    Scenario(
        key="correction_cc_not_price",
        title="«не 200000 VND, а обьем … до 200 кубических сантиметров»",
        steps=(
            Says("найди мне моцокил 200 кубиков. какие есть сейчас"),
            Taps("nha_trang"),
            Taps(SKIP),
            Says("не 200000 VND, а обьем мощность двигателя до 200 кубических сантиметров"),
        ),
        max_questions_before_results=2,
        # Пожелание выполнено 03.09.2026 и переехало сюда, в ожидания: теперь
        # регресс красит тест. Что было: поправка читалась НОВЫМ запросом (она
        # приносит содержательные слова — «кубических», «сантиметров»), начиналась
        # новая цепочка версий, и категория из первого сообщения исчезала —
        # человек объяснил, что его поняли не так, и получил сброс. Отличает
        # поправку противопоставление «не X, а Y» (`dialogue.corrects`), а факты
        # сливает `merge_edit` — тот же, что у ответа словами.
        #
        # Город здесь тоже обязан выжить, и это не украшение ожиданий: он был
        # назван КНОПКОЙ, то есть собранным ответом, а не текстом запроса. Если
        # поправка его теряет, клиенту придётся отвечать на тот же вопрос второй
        # раз — ровно то, за что в этом проекте считают вопросы.
        expect={
            "category": "motorbike",
            "city": "nha_trang",
            "attributes.engine_cc": 200,
            # «до 200» — верхняя граница, а не точка: направление поправка
            # доносит вместе с числом.
            "attributes.engine_cc_dir": "max",
        },
        forbid=("budget.max",),
    ),
)

# ── 4. Расплывчатый: здоровается, торопится, просит «самое дешёвое» ──────────
#
# «привет» отдельным сообщением — тоже из журнала. Здесь проверяется не разбор,
# а то, что бот не тратит ход на пустое приветствие и не заваливает вопросами
# того, кто и так сказал мало.

VAGUE = (
    Scenario(
        key="vague_hello_then_scooter",
        title="«привет», потом «нужен скутер» — и ничего больше",
        steps=(Says("привет"), Says("нужен скутер"), Taps("nha_trang"), Taps(SKIP)),
        # Три, а не два, и это не поблажка. «Привет» не несёт ни одного факта, и
        # «Что ищем?» на него — верный ответ, а не лишний вопрос: промолчать
        # хуже. Дальше идут город и бюджет, которых человек не назвал. Ставить
        # здесь два значило бы требовать от бота угадать предмет по «привет».
        max_questions_before_results=3,
        expect={"category": "motorbike"},
    ),
    Scenario(
        key="vague_cheapest",
        title="«а покажи самые дешевый скутеры которые есть на продажу»",
        steps=(
            Says("а покажи самые дешевый скутеры которые есть на продажу"),
            Taps("nha_trang"),
            Taps(SKIP),
        ),
        max_questions_before_results=2,
        expect={"category": "motorbike", "intent": "buy"},
        # «Самые дешёвые» — это про порядок выдачи, а не сумма: бюджета клиент
        # не назвал, и придумывать его за него нельзя.
        forbid=("budget.max",),
    ),
)

# ── 5. Жилец: много условий сразу, потом передумывает ───────────────────────
#
# В журнале жильё есть (`cat=apartment` с городом и бюджетом), но короткое.
# Формулировки достроены по рынку Нячанга: комнаты, мебель, вид на море — то,
# чем в объявлениях действительно торгуют (`market_terms`, атрибуты жилья).

HOUSING = (
    Scenario(
        key="housing_two_bedrooms",
        title="«сниму квартиру в нячанге до 10 млн донгов, 2 спальни, с мебелью»",
        steps=(Says("сниму квартиру в нячанге до 10 млн донгов, 2 спальни, с мебелью"),),
        max_questions_before_results=1,
        expect={
            "category": "apartment",
            "city": "nha_trang",
            "budget.max": 10_000_000.0,
            "attributes.rooms": 2,
        },
    ),
    Scenario(
        key="housing_changes_mind",
        title="сначала двушка, потом «нет, лучше студию у моря»",
        steps=(
            Says("сниму квартиру в нячанге до 10 млн донгов, 2 спальни"),
            Says("нет, лучше студию у моря"),
        ),
        max_questions_before_results=2,
        expect={"category": "apartment", "attributes.sea_view": True},
        expect_results=None,
        wish=Wish(
            fields={"city": "nha_trang", "budget.max": 10_000_000.0},
            why=(
                "«нет, лучше студию у моря» — смена решения в той же просьбе, но "
                "детектор поправок её не узнаёт: он опознаёт противопоставление "
                "«не X, а Y», а здесь «нет, лучше X». И это осознанно. Форма «не "
                "X, а Y» встречена в журнале бота живьём (дважды), а «нет, лучше» "
                "придумана мной при постройке этой персоны — расширять детектор "
                "по выдуманной фразе значит гадать, а цена ложной поправки "
                "конкретна: новый запрос примут за уточнение и молча продолжат "
                "искать прежнее. Появится «нет, лучше» в журнале — добавим форму "
                "и это пожелание переедет в ожидания"
            ),
        ),
    ),
)

PERSONAS: tuple[Scenario, ...] = TERSE + TYPING + CORRECTING + VAGUE + HOUSING
