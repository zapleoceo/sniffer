"""Симулятор диалога: качество разговора в цифрах, а не на глаз.

Жалоба владельца звучит так: бот «тупит» — задаёт лишние вопросы и показывает
не то. Проверять это глазами нельзя по двум причинам. Первая: «стало лучше» —
не факт, а впечатление, и после третьей правки оно перестаёт быть общим.
Вторая: регресс в диалоге не виден в юнит-тестах. Каждый из них проверяет свой
случай и остаётся зелёным, пока набор случаев в сумме не превратится в допрос.

Поэтому здесь прогоняются РЕАЛЬНЫЕ формулировки рынка Нячанга (включая
дословные фразы из лога владельца) через настоящий `Conversation`, и с каждой
снимаются числа: сколько вопросов прозвучало до первой выдачи, дошло ли дело до
карточек, что распозналось в паспорте, сколько показанного противоречит
запросу.

Что подделано и что нет
-----------------------

Настоящие: `Conversation`, разбор запроса (`intake_rules`), домен диалога
(вопросы, обратная связь, повторы), ранжирование выдачи, рендер карточек,
верификатор живости. Именно они и меряются.

Подделаны ровно три вещи, и все три — выход наружу: сеть (`market.py` вместо
источников), модель (`intake_rules` вместо LLM — разбор по правилам работает и
в бою, когда брокер лежит) и Postgres (`stubs.py`). Ни один шаг воронки, кроме
них, не подменён: подмена решения означала бы, что харнес меряет собственную
подделку.

Почему в `src/`, а не в `scripts/`
----------------------------------

Потребителей два: `tests/test_simulation.py` (защита от регрессий в CI) и
владелец, которому нужен отчёт глазами. Общий у них — не код запуска, а
ТАБЛИЦА СЦЕНАРИЕВ: она и есть определение того, что здесь считается хорошим
диалогом. Второй её копии быть не должно, а импортировать из `tests/` нечего:
образ тесты не везёт.

И это же решает, где отчёт запускается. CLAUDE.md требует проверять деплой
после каждого мержа, потому что зелёный CI не означает, что изменение доехало.
Инструмент, живущий в `tests/`, ответить на вопрос «а на сервере-то как?» не
может физически — в контейнере его нет. Отсюда `python -m sniffer.simulation`:
ту же таблицу можно прогнать по коду, который реально развёрнут.

Слоем симулятор не является и в таблицу слоёв CLAUDE.md не входит — своей
предметной логики у него нет, он собирает чужую. По устройству это шестая точка
входа рядом с `bot`, `collector`, `worker`, `notifier`, `dashboard`, только не
сервис: отработала и вышла.

Описание метрик и разбор красных сценариев — `docs/passport.md`, раздел
«Симуляция диалога».
"""

