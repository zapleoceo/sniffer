"""Число комнат из текста — общее знание запроса, ответа и лота.

Отдельный модуль (`search.rooms`), как `engine_size`: число комнат — атрибут-ЧИСЛО,
и читается на обеих сторонах воронки одним знанием. Здесь проверяется то, из-за
чего жёсткий фильтр мог бы ошибиться: голое число комнатой считать нельзя, а
подвальное меню агентства («квартиры и студии») — не описание лота.
"""

from __future__ import annotations

import pytest

from sniffer.search.rooms import read_rooms, room_counts


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("студия", 1),
        ("студию у моря", 1),
        ("однушка", 1),
        ("однокомнатная квартира", 1),
        ("1 спальня", 1),
        ("1 bedroom apartment", 1),
        ("2 спальни", 2),
        ("2спальни", 2),
        ("2-комнатная", 2),
        ("двушка в центре", 2),
        ("2BR", 2),
        ("2 bedroom", 2),
        ("2 комнаты", 2),
        ("3 спальни", 3),
        ("трёшку у моря", 3),
        ("3-bedroom", 3),
        ("3bed", 3),
        ("4 спальни", 4),
    ],
)
def test_read_rooms_from_the_natural_forms(text: str, expected: int) -> None:
    """Так число комнат пишут на рынке: словом, цифрой со словом, латиницей."""
    assert read_rooms(text) == expected


@pytest.mark.parametrize(
    "text",
    [
        "",
        "квартира у моря",
        "honda 2 owners",
        "оплата за 2 месяца",
        "5 минут до моря",
        "70м2, балкон",
        "2 ванные комнаты",
    ],
)
def test_a_bare_or_unrelated_number_is_not_a_room_count(text: str) -> None:
    """Голое число — не комната: год, цена, минуты, санузлы тоже числа.

    «2 ванные комнаты» проверяет прилегание: «2» относится к «ванные», а не к
    «комнаты», и комнатой не читается — иначе санузлы стали бы спальнями.
    """
    assert read_rooms(text) is None


def test_an_explicit_count_overrides_an_agency_menu_word() -> None:
    """Явное «2 спальни» главнее слова «студии» в подвале-меню (замер снимка).

    У 17 агентских лотов из 200 в подвале стоит «квартиры и студии» — навигация,
    а не описание. Прижатое число подвал не пачкает, поэтому оно и главнее.
    """
    assert room_counts("Квартира 2 спальни у моря. Ещё варианты: квартиры и студии") == [2]


def test_a_studio_word_alone_is_one_room() -> None:
    """Настоящая студия своё число не пишет — тогда читается слово."""
    assert room_counts("Сдаётся студия у моря, 30 м²") == [1]


def test_several_explicit_counts_are_all_read() -> None:
    """Лот вправе рекламировать несколько вариантов — читаем все, по порядку."""
    assert room_counts("варианты: 1 спальня, 2 спальни и 3 спальни") == [1, 2, 3]
